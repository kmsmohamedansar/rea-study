#include <stdio.h>
/* a message stored XOR-masked with 0x5A. The program decodes and prints it. */
static const unsigned char blob[] = {0x2f,0x2a,0x3e,0x3b,0x2e,0x3f,0x74,0x3f,0x22,0x3b,0x37,0x2a,0x36,0x3f,0x74,0x33,0x34,0x2c,0x3b,0x36,0x33,0x3e};
int main(void) {
    for (unsigned i = 0; i < sizeof blob; i++) putchar(blob[i] ^ 0x5A);
    putchar('\n');
    return 0;
}
